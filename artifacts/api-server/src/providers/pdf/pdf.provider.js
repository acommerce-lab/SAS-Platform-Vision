/**
 * PDF generation provider.
 * Uses a lightweight HTML-to-PDF approach via embedded HTML template.
 * Puppeteer is used when available; falls back to base64-encoded HTML otherwise.
 */

import { logger } from '../../lib/logger.js';

let puppeteerAvailable = false;

export async function initPdf() {
  try {
    await import('puppeteer');
    puppeteerAvailable = true;
    logger.info('PDF provider ready (Puppeteer)');
  } catch {
    logger.warn('Puppeteer not available — PDF generation will return HTML fallback');
  }
}

/**
 * Generate waybill PDF.
 *
 * @param {{ shipment: object, waybill: object }} data
 * @returns {Promise<Buffer>} PDF buffer (or HTML buffer as fallback)
 */
export async function generateWaybillPdf({ shipment, waybill }) {
  const html = renderWaybillHtml({ shipment, waybill });

  if (!puppeteerAvailable) {
    logger.debug('Returning HTML fallback for waybill PDF');
    return Buffer.from(html, 'utf8');
  }

  const { default: puppeteer } = await import('puppeteer');
  const browser = await puppeteer.launch({ args: ['--no-sandbox', '--disable-setuid-sandbox'] });
  const page = await browser.newPage();

  try {
    await page.setContent(html, { waitUntil: 'networkidle0' });
    const pdf = await page.pdf({ format: 'A4', printBackground: true });
    return pdf;
  } finally {
    await browser.close();
  }
}

function renderWaybillHtml({ shipment, waybill }) {
  const fmt = (v) => v ?? '—';
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <title>Waybill ${waybill.waybill_number}</title>
  <style>
    body { font-family: Arial, sans-serif; font-size: 12px; margin: 40px; color: #111; }
    h1 { font-size: 24px; margin-bottom: 4px; }
    .subtitle { color: #555; margin-bottom: 24px; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 24px; }
    th { text-align: left; background: #f0f0f0; padding: 6px 10px; border: 1px solid #ccc; }
    td { padding: 6px 10px; border: 1px solid #ccc; }
    .footer { margin-top: 40px; font-size: 10px; color: #999; }
  </style>
</head>
<body>
  <h1>SAS Platform — Waybill</h1>
  <div class="subtitle">Waybill #${waybill.waybill_number} | Issued: ${new Date(waybill.issued_at).toLocaleDateString()}</div>

  <table>
    <tr><th colspan="2">Shipment Information</th></tr>
    <tr><td>Reference</td><td>${fmt(shipment.reference_number)}</td></tr>
    <tr><td>Status</td><td>${fmt(shipment.status)}</td></tr>
    <tr><td>Pickup</td><td>${fmt(shipment.pickup_location)}</td></tr>
    <tr><td>Dropoff</td><td>${fmt(shipment.dropoff_location)}</td></tr>
    <tr><td>Cargo</td><td>${fmt(shipment.cargo_description)}</td></tr>
    <tr><td>Vehicle Type</td><td>${fmt(shipment.required_vehicle_type)}</td></tr>
    <tr><td>Vehicle Category</td><td>${fmt(shipment.required_vehicle_category)}</td></tr>
    <tr><td>Distance</td><td>${shipment.distance_km ? `${shipment.distance_km} km` : '—'}</td></tr>
    <tr><td>Quoted Price</td><td>${shipment.quoted_price ? `${shipment.quoted_price} ${shipment.currency}` : '—'}</td></tr>
  </table>

  <div class="footer">
    Generated by SAS Platform | ${new Date().toISOString()}
  </div>
</body>
</html>`;
}
